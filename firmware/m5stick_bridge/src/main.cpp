// M5StickS3 push-to-talk mic/speaker bridge for bridge_server.py.
//
// Protocol over one WebSocket connection (raw PCM s16le mono @ SAMPLE_RATE
// both ways, framed with tiny text control messages):
//   BtnA held   -> client sends text "start", then binary mic chunks
//   BtnA release-> client sends text "stop"
//   server sends text "heard:<transcript>" as soon as STT finishes (not
//     truly live/word-by-word — faster-whisper transcribes a completed
//     utterance, not a stream — but prompt: it arrives right as listening
//     ends and thinking begins), then "reply:<text>", then binary audio
//     chunks, then "end" -> client plays the buffered reply. A reply text
//     starting with "(" is bridge_server.py's error-sentinel convention
//     ("(ollama error: ...)", "(didn't catch that)") — used here to pick
//     ERROR vs DONE once playback finishes.
//
// BtnA pressed while SPEAKING -> stops playback cleanly (interrupt) instead
//   of starting a new recording immediately, since the mic and speaker share
//   one I2S codec and switching modes mid-playback glitches the audio.
// BtnA tap (otherwise)   -> cycles the display: Rina's face -> clock ->
//   pomodoro timer -> back to Rina. A tap and a hold look identical at the
//   instant of the press, so recording waits out TALK_HOLD_MS before it
//   starts; see clock_face.h and pomodoro_face.h for the two alt screens.
// BtnB click       -> reset conversation history (tells the server) on
//   Rina's face or the clock; starts/pauses the countdown on the pomodoro
//   screen instead, since there is no conversation in view there to reset
//   (double click resets the pomodoro timer to 50:00 there instead).
// Powering off is the physical power button (double-click it) -- a real
// PMIC-level power-off, confirmed against M5Stack's own docs
// (docs.m5stack.com/en/arduino/m5sticks3/button). BtnB long-press used to
// trigger ESP32 deep sleep as a software-only substitute, from before that
// button's real behavior was verified; removed 2026-09-15 now that the
// power button covers this properly (and more deeply -- true PMIC power-off
// draws less than ESP32 deep sleep, which still keeps the RTC/wake domain
// powered).
//
// The face is the Catppuccin Macchiato pixel-art sprite sheet (sprites.h,
// generated by tools/make_face_sprites.py from a reference PNG). Display is
// split into three independent components, each its own function: the
// character sprite, a small status line (procedural glyph, since the
// default font has no ● ◆ ♪), and a caption text area (transcript while
// listening/thinking, response while speaking/done) — none of them baked
// into the sprite images themselves. Everything drawn here (state, mic/TTS
// amplitude, transcript/response text) is already local to the Stick or
// arrives over the protocol above; nothing needs a new round-trip to render.
