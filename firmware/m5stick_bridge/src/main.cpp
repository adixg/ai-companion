// briefly show a state, then auto-revert to idle after `ms` — guarded by
// transientState so an unrelated uiState change in the meantime (e.g. the
// Wi-Fi dropping mid-transient) doesn't get silently clobbered back to IDLE
// when this deadline fires; see loop().
static void showTransient(UiState st, uint32_t ms) {
  uiState = st;
  transientState = st;
  transientUntil = millis() + ms;
  setStatus(statusFor(st).text);
}

